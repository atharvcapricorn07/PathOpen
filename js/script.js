// --- Anonymous device tracking (no login, just a local ID) ---
function getDeviceId() {
  let id = localStorage.getItem('pathable_device_id');
  if (!id) {
    id = crypto.randomUUID();
    localStorage.setItem('pathable_device_id', id);
  }
  return id;
}

